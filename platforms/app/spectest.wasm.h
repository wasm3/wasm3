//
//  spectest.wasm.h
//
//  The "spectest" module the WebAssembly spec testsuite imports from, as the
//  reference interpreter defines it. The spec repl loads it and registers it
//  under that name, so a module importing from "spectest" links against a real
//  module: host functions can stand in for the print functions, but nothing can
//  stand in for an exported memory or table.
//
//  The print functions have empty bodies on purpose - the testsuite only cares
//  that the call links and returns, never about the output.
//
//  A d_m3HasFloat=0 build has no f32.const / f64.const to initialize the two
//  float globals with, so it gets the same module without them. Their exports
//  go too, which is right: nothing in such a build could read them. The float
//  parameter types are kept - they parse fine, only the operations are gone.
//
//  To regenerate: save the module above as spectest.wat, then
//      wat2wasm spectest.wat -o spectest.wasm && xxd -i spectest.wasm

/*
(module
  (func (export "print"))
  (func (export "print_i32")     (param i32))
  (func (export "print_i64")     (param i64))
  (func (export "print_f32")     (param f32))
  (func (export "print_f64")     (param f64))
  (func (export "print_i32_f32") (param i32 f32))
  (func (export "print_f64_f64") (param f64 f64))

  (table  (export "table")  10 20 funcref)
  (memory (export "memory") 1 2)

  (global (export "global_i32") i32 (i32.const 666))
  (global (export "global_i64") i64 (i64.const 666))
  (global (export "global_f32") f32 (f32.const 666.6))
  (global (export "global_f64") f64 (f64.const 666.6))
)
*/

